package io.jababa.lost_batalion;

/**
 * Сторона конфлікту. Сторін завжди дві — сині й червоні, — скільки б гравців
 * за них не грало.
 *
 * <p>Назви лишились із одиночної гри й тепер трохи вводять в оману: для гостя
 * «ENEMY» — це його власна армія. Перейменування зачепило б асети і половину
 * рендеру, тому лишилось як є.
 *
 * <h3>Чому тут більше немає {@code forPlayer(int)}</h3>
 * До 5 на 5 сторона й номер гравця були тим самим числом: гравець 0 — сині,
 * гравець 1 — червоні. Тепер за одну сторону грає до п'яти гравців, і ця
 * рівність зникла. Перетворення playerId → сторона живе в
 * {@code sim.PlayerRoster} і НІДЕ більше; {@link #byIndex(int)} тут — це
 * індекс САМОЇ сторони (0 або 1), а не номер гравця. Стара пара методів
 * {@code forPlayer}/{@code playerId} прибрана навмисно: лишись вона, кожне
 * місце, де її забули замінити, тихо працювало б неправильно рівно з третього
 * гравця.
 */
public enum Team {
    PLAYER,
    ENEMY;

    /** Сторона за власним індексом: 0 — сині, 1 — червоні. */
    public static Team byIndex(int index) {
        return index == 0 ? PLAYER : ENEMY;
    }

    /** Індекс сторони: 0 або 1. Ним індексуються масиви рахунку, точок, втрат. */
    public int index() {
        return this == PLAYER ? 0 : 1;
    }

    /** Протилежна сторона. Сторін дві, тож вона єдина. */
    public Team opponent() {
        return this == PLAYER ? ENEMY : PLAYER;
    }
}
