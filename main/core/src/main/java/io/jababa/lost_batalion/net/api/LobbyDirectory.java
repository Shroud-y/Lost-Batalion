package io.jababa.lost_batalion.net.api;

import java.util.List;

/**
 * Джерело списку доступних лоббі.
 *
 * <p>Винесено в інтерфейс, щоб спосіб пошуку можна було замінити, не чіпаючи
 * екран: зараз це широкомовний UDP по локальній мережі, а якщо колись знадобиться
 * центральний реєстр для гри через інтернет — міняється одна реалізація.
 */
public interface LobbyDirectory {

    /** Почати слухати мережу. Ідемпотентний. */
    void start();

    /** Зупинити і звільнити сокети. */
    void stop();

    /** Позачергове сканування — кнопка «Оновити». */
    void refresh();

    /**
     * Поточний список, відсортований стабільно (за назвою лоббі, потім за адресою),
     * щоб рядки не стрибали між кадрами при кожному оновленні.
     */
    List<DiscoveredLobby> getLobbies();

    /** Чи триває зараз сканування — для індикатора в UI. */
    boolean isScanning();
}
