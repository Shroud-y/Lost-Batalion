package io.jababa.lost_batalion.sim;

/**
 * Темп симуляції.
 *
 * <p>Живе в пакеті симуляції, а не мережі, бо це властивість гри, а не
 * транспорту: фіксований крок потрібен навіть в одиночному матчі, щоб бій
 * розвивався однаково на 60 і на 144 кадрах. Мережа лише переносить ці числа
 * у StartMatch, щоб клієнт із іншою збіркою відвалився одразу.
 */
public final class TickRate {

    private TickRate() {}

    /** Тіків симуляції на секунду. */
    public static final int   TICKS_PER_SECOND = 40;

    /** Тривалість тіку в мілісекундах. */
    public static final long  TICK_MILLIS = 1000L / TICKS_PER_SECOND;   // 25

    /**
     * Тривалість тіку в секундах — крок, який симуляція використовує ЗАВЖДИ.
     * Реальний час кадру в симуляцію не потрапляє взагалі: варіативний delta
     * означав би, що юніт із повільнішим комп'ютером проходить іншу відстань.
     */
    public static final float TICK_SECONDS = 1f / TICKS_PER_SECOND;

    /**
     * Той самий крок, але точним типом — для годинника, що набирає реальний час.
     *
     * <p>{@link #TICK_SECONDS} як float дорівнює 0.025000000372…, тобто трохи
     * БІЛЬШЕ за чверть сотої. Дрібниця, поки крок один; але годинник порівнює
     * з ним накопичену суму сотень кадрів, і надлишок множиться на кількість
     * тіків: за десять секунд при 144 Гц набігав рівно один загублений тік.
     * Симуляція живе з float-кроком (він однаковий у всіх), а годинник —
     * з цим.
     */
    public static final double TICK_SECONDS_EXACT = 1.0 / TICKS_PER_SECOND;

    /**
     * Затримка виконання команди. Наказ, відданий під час тіку N, виконується
     * на тіку N + INPUT_DELAY_TICKS одночасно в усіх.
     */
    public static final int INPUT_DELAY_TICKS = 2;

    /**
     * Скільки тіків максимум наздоганяти за один кадр рендеру.
     *
     * <p>Без обмеження після зависання на секунду накопичилось би 40 тіків,
     * їх обробка зайняла б ще більше часу, накопичилось би ще більше — це
     * «спіраль смерті», з якої гра сама не виходить. Краще з'їсти
     * сповільнення на секунду, ніж зависнути назавжди.
     */
    public static final int MAX_CATCHUP_TICKS = 8;
}
