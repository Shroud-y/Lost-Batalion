package io.jababa.lost_batalion.net.commands;

/**
 * Наказ гравця — єдине, що взагалі їздить по мережі під час матчу.
 *
 * <p>Позиції, HP і решта стану НЕ передаються ніколи: кожен клієнт отримує той
 * самий потік команд і сам відтворює однаковий стан. Тому команда мусить бути
 * повністю самодостатньою — жодних посилань на локальні об'єкти, лише id та
 * координати у fixed-point.
 *
 * <p>Підкласи зобов'язані мати публічний конструктор без аргументів: Kryo
 * створює екземпляр перед тим, як заповнити поля.
 */
public abstract class GameCommand {

    /** Хто віддав наказ. Заповнює клієнт, хост перевіряє при ретрансляції. */
    public int playerId;

    protected GameCommand() {}

    protected GameCommand(int playerId) {
        this.playerId = playerId;
    }

    /** Застосувати наказ до симуляції. Викликається строго на тіку виконання. */
    public abstract void execute(CommandContext ctx);
}
