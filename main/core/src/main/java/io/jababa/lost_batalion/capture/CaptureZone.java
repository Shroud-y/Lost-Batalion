package io.jababa.lost_batalion.capture;

/**
 * Опис однієї точки захоплення так, як його задає сценарій.
 *
 * <p>Це АВТОРСЬКІ дані, а не похідні від маски. Раніше точки будувались із
 * плям VILLAGE у масці лісу, а зоною було коло сталого радіуса — форма села
 * при цьому ні на що не впливала, і межа захоплення могла лежати посеред
 * річки або зрізати половину хат. Тепер межу задає той, хто малює карту.
 *
 * <p>Чотирикутник, а не коло чи довільний багатокутник: чотирьох вершин
 * вистачає, щоб повторити форму села й притулити межу до дороги, і при цьому
 * перевірка входження лишається чотирма порівняннями без циклу по змінній
 * кількості ребер.
 *
 * <h3>Детермінізм</h3>
 * Вершини — константи в коді, тобто однакові на всіх клієнтах за побудовою.
 * Саме тому в знімок стану вони не їдуть: там лишаються тільки прогрес і
 * власник, як і було з кола́ми.
 *
 * <h3>Вимоги до форми</h3>
 * Чотирикутник має бути ОПУКЛИМ і без самоперетинів — перевірка входження
 * ({@link CapturePoint#contains}) працює за знаком векторного добутку і на
 * увігнутій формі дала б хибний результат. Обхід вершин може бути будь-який,
 * за годинниковою чи проти.
 */
public final class CaptureZone {

    /**
     * Коротка позначка точки — те, що бачить гравець у HUD («A», «B», «C»).
     *
     * <p>Належить сценарію, а не порядковому номеру в списку: підпис мусить
     * лишатись тим самим, навіть якщо точки колись переставлять місцями.
     */
    public final String name;

    /** Вершини в СВІТОВИХ пікселях (Y вгору), підряд: x0,y0, x1,y1, x2,y2, x3,y3. */
    public final int[] corners;

    /**
     * @param corners рівно 8 чисел — чотири вершини опуклого чотирикутника
     */
    public CaptureZone(String name, int... corners) {
        if (corners == null || corners.length != 8) {
            throw new IllegalArgumentException(
                "Зона захоплення описується рівно чотирма вершинами (8 чисел), а не "
                    + (corners == null ? 0 : corners.length));
        }
        this.name    = name;
        this.corners = corners;
    }
}
