package io.jababa.lost_batalion.capture;

import io.jababa.lost_batalion.Team;

/**
 * Стратегічна точка — село на карті, яке можна захопити.
 *
 * <p>Центр береться з маски лісу (колір #F0FF00), радіус спільний для всіх
 * точок. Важливо: захоплює той, хто зайшов у КОЛО точки, а не той, хто ступив
 * на пікселі села в масці. Пляма села має довільну форму й місцями завширшки в
 * кілька пікселів — ловити вхід по ній означало б, що юніт «то в точці, то ні»
 * на кожному кроці.
 *
 * <p>Весь стан цілочисельний і входить у checksum: захоплення змінює хід матчу,
 * тож розійтись у ньому не можна так само, як у позиціях юнітів.
 */
public class CapturePoint {

    /** Центр кола, Q47.16. */
    public final long x, y;

    /** Хто вже володіє точкою; {@code null} — нейтральна. */
    public Team owner;

    /**
     * Чий прогрес зараз накопичений. Може не збігатися з {@link #owner}: поки
     * чужа сторона стоїть у колі, спершу зривається старе володіння
     * ({@code progress} падає до нуля), і лише потім починає рости нове.
     */
    public Team holder;

    /** Накопичений прогрес у «одиницях захоплення», 0..{@link CaptureManager#FULL}. */
    public int progress;

    public CapturePoint(long x, long y) {
        this.x = x;
        this.y = y;
    }

    /** Частка заповнення кола, 0..1 — лише для рендеру. */
    public float fill() {
        return progress / (float) CaptureManager.FULL;
    }
}
