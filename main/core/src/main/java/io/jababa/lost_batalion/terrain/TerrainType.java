package io.jababa.lost_batalion.terrain;

/**
 * Типи місцевості що визначаються за кольором маски.
 *
 * Коди для зручності:
 *   LOWLANDS     = 1а  (нізіни)
 *   PRE_LOWLANDS = 1б  (перед нізіни)
 *   PLAINS       = 2а  (рівнини)
 *   PLAINS_ALT   = 2б  (рівнини хз)
 *   PRE_HIGHLANDS= 3а  (перед височини)
 *   HIGHLANDS    = 3б  (височини)
 *   FOREST           (ліс — окрема маска)
 *   VILLAGE          (село — стратегічна точка, у масці лісу)
 */
public enum TerrainType {
    NONE,
    FOREST,
    RIVER,
    LOWLANDS,       // 1а — нізіни
    PRE_LOWLANDS,   // 1б — перед нізіни
    PLAINS,         // 2а — рівнини
    PLAINS_ALT,     // 2б — рівнини хз
    PRE_HIGHLANDS,  // 3а — перед височини
    HIGHLANDS,      // 3б — височини

    /**
     * Село — стратегічна точка захоплення. Намальоване в масці ЛІСУ кольором
     * #F0FF00. На рух і бій не впливає: це не місцевість, а мітка «тут стоїть
     * село», з якої будуються точки захоплення (див. {@code capture/}).
     *
     * <p>Додано в кінець навмисно: ordinal типу лежить у {@code typeGrid}, і
     * вставка посередині мовчки перемішала б усі попередні значення.
     */
    VILLAGE
}
