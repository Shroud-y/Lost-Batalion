package io.jababa.lost_batalion.net.api;

/**
 * Спосіб, у який гра знаходить супротивника і возить до нього байти.
 *
 * <p>Зараз таких способів два: широкомовний UDP у локальній мережі
 * ({@code LanBackend}) і Steam. Вони не альтернативні реалізації одного й того
 * самого — вони РІЗНІ мережі: у LAN лоббі знаходять розсилкою в підмережі, у
 * Steam його віддає сервіс матчмейкінгу, і адреса там не IP, а SteamID64.
 * Спільне в них рівно те, що описано в {@link LobbySession} і
 * {@link MatchTransport}, і саме на цьому рівні їх бачить решта гри.
 *
 * <p>Реалізація Steam НЕ може жити в {@code core}: модуль {@code :android}
 * залежить від core, а нативів Steam на Android не існує. Тому бекенди
 * реєструються ззовні — десктопний лаунчер додає свій до
 * {@link MultiplayerServices} перед створенням гри, а всі екрани далі просять
 * поточний. Той самий прийом, що з ботом: він теж ПІР, а не частина ядра.
 */
public interface NetBackend {

    /**
     * Стійкий ідентифікатор для збереження вибору.
     *
     * <p>Саме id, а не порядковий номер у списку: список бекендів залежить від
     * того, що зареєстрував лаунчер, тож індекс у ньому мінявся б від збірки до
     * збірки й тихо перемикав гравцеві вибір. Те саме правило, що в
     * {@code Settings.getBotDifficulty}.
     */
    String id();

    /** Назва для перемикача в меню. У верхньому регістрі — див. DESIGN §3. */
    String label();

    /**
     * Чи можна зараз ним користуватись.
     *
     * <p>Недоступний бекенд НЕ зникає з меню, а гасне (DESIGN §7): зникнення
     * рядка читається як помилка інтерфейсу, а «Steam не запущено» — це стан,
     * який гравець може виправити, не виходячи з гри.
     */
    boolean isAvailable();

    /** Чому недоступний. Показується поруч із згаслим пунктом; null якщо все гаразд. */
    String unavailableReason();

    LobbyDirectory createDirectory();

    LobbySession host(String lobbyName, String nick, String scenarioId, int maxPlayers);

    LobbySession join(DiscoveredLobby lobby, String nick);

    /**
     * Приєднатись за введеним вручну рядком: IP[:порт] для LAN, SteamID64 або
     * ключ кімнати для Steam. Що саме означає рядок — знає лише бекенд, тому
     * і підказку для поля вводу дає він же.
     */
    LobbySession joinByAddress(String address, String nick);

    /** Підказка в порожньому полі прямого підключення (напр. {@code 192.168.0.5}). */
    String addressHint();

    /**
     * Нік за замовчуванням, якщо гравець свого ще не вводив. LAN не знає імені
     * гравця й повертає порожній рядок; Steam підставляє персону.
     */
    String defaultNick();

    /**
     * Чи має ця мережа поняття «ключ кімнати».
     *
     * <p>У локальній мережі його немає й бути не може: там видно рівно тих, хто
     * в одній підмережі, і звужувати нічого. У Steam лоббі шукаються по всьому
     * світу, тож потрібен спосіб сказати «мені оце, а не всі».
     *
     * <p>Від цього залежить, чи є на екрані поле ключа — тобто UI питає МЕРЕЖУ,
     * а не перевіряє її назву.
     */
    default boolean usesRoomKey() { return false; }

    /** Звузити пошук до однієї кімнати. Порожній рядок — показувати всі. */
    default void setSearchKey(String key) { }

    /**
     * Ключ кімнати, яку ми ЗАРАЗ хостимо, — його показує екран лоббі, щоб
     * гравець продиктував супернику. Порожній, якщо ми не хост або мережа
     * ключів не має.
     */
    default String hostedRoomKey() { return ""; }

    /**
     * Що написати, коли список лоббі порожній.
     *
     * <p>Текст належить мережі, а не екрану: «хост має бути в тій самій
     * локальній мережі» і «перевір ключ кімнати» — поради про різні речі, і
     * єдиний екран не має вибирати між ними за назвою бекенда.
     */
    String emptyListHint();

    /**
     * Дати бекенду попрацювати. Викликається РАЗ НА КАДР із
     * {@code LostBatalion.render()}, а не з мережевого екрана.
     *
     * <p>Місце принципове: Steam доставляє і події лоббі, і P2P-пакети матчу
     * лише зсередини {@code SteamAPI.runCallbacks()}. Прив'язати виклик до
     * екрана лоббі означало б, що в матчі не приходить нічого взагалі.
     */
    void pump();
}
