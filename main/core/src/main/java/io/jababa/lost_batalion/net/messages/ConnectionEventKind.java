package io.jababa.lost_batalion.net.messages;

/** Що саме сталося зі з'єднанням гравця. Визначає, який текст показує UI. */
public enum ConnectionEventKind {
    /**
     * Гравець підключений, але його команди не приходять вчасно — матч чекає.
     * Це не помилка, а штатна поведінка lockstep; повідомлення потрібне лише
     * щоб решта розуміла, чому гра «підвисла», і бачила винуватця.
     */
    LAGGING,
    /** TCP-з'єднання розірвано. Слот тримається під перепідключення. */
    DISCONNECTED,
    /** Гравець повернувся і отримав знімок стану. */
    RECONNECTED,
    /** Хост вирішив продовжити без нього — слот звільнено остаточно. */
    DROPPED,
    /** Гравець сам вийшов із матчу. */
    LEFT
}
