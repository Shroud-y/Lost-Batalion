package io.jababa.lost_batalion.net.messages;

/**
 * Хост → усім: повний знімок стану симуляції, з якого треба продовжити.
 *
 * <p>Надсилається всім, а не лише десинхронізованому. Так простіше зробити
 * надійно: після застосування знімка всі гарантовано в одному стані, і не треба
 * доводити, що стан «здорових» клієнтів справді ідентичний хостовому — після
 * розбіжності це вже не самоочевидно.
 *
 * <p>Стан їде як {@code byte[]}, а не як граф об'єктів: формат знімка описаний
 * в одному місці (клас знімка симуляції) і не залежить від того, як Kryo
 * вирішить обійти посилання між юнітами й наказами.
 */
public class ResyncSnapshot {

    /** Тік, стану на кінець якого відповідає знімок. Симуляція продовжиться з tick+1. */
    public int tick;

    /** Серіалізований стан: юніти, накази, RNG, лічильники. */
    public byte[] state;

    /** Хеш цього ж стану — приймач звіряє після розпакування, що знімок доїхав цілим. */
    public long checksum;

    public ResyncSnapshot() {}

    public ResyncSnapshot(int tick, byte[] state, long checksum) {
        this.tick     = tick;
        this.state    = state;
        this.checksum = checksum;
    }
}
