package io.jababa.lost_batalion.net.api;

import com.badlogic.gdx.graphics.Texture;

/**
 * Звідки беруться аватарки учасників.
 *
 * <p>Джерело належить МЕРЕЖІ, а не екрану, з тієї ж причини, що й нік за
 * замовчуванням: у Steam картинка є, у локальній мережі її немає й узятись їй
 * нізвідки. Тому екран питає {@link NetBackend#avatars()}, а не перевіряє назву
 * бекенда.
 *
 * <h3>Асинхронність — головне тут</h3>
 * Steam віддає аватарку не одразу: на першому запиті її може не бути взагалі, а
 * приходить вона за кілька кадрів. Тому {@link #avatarFor(String)} має право
 * повернути {@code null}, і це НЕ помилка — це «ще нема». Щоб екран дізнався,
 * коли картинка нарешті з'явилась, є {@link #revision()}: лічильник зростає на
 * кожну нову аватарку, і той, хто малює, просто звіряє його щокадру. Підписки з
 * відписками тут були б надлишкові: читач один, і він і так має кадровий такт.
 *
 * <p><b>Колбека для цього НЕ досить, і це виміряно.</b> Steam цілком може
 * дістати аватарку мовчки: наступний запит уже віддає картинку, а
 * {@code onAvatarImageLoaded} не приходить взагалі (перевірено зондом на
 * «холодному» акаунті — аватарка з'явилась, жодного колбека). Оскільки екран
 * перепитує лише тоді, коли перемальовує рядки, а перемальовує їх лише коли
 * змінився {@code revision}, гра застрягла б у стані «літера назавжди» при
 * готовій картинці. Тому джерело ще й САМО перевіряє очікуване — у
 * {@link #update()}.
 *
 * <h3>Хто володіє текстурами</h3>
 * Джерело. Воно живе стільки ж, скільки бекенд, тобто ПЕРЕЖИВАЄ і екран лоббі,
 * і матч. Це навмисно: аватарка потрібна і в кімнаті, і в HUD бою, і
 * перезавантажувати її на кожній зміні розміру вікна означало б смикати Steam на
 * рівному місці. Викликач текстуру НЕ звільняє — тільки малює.
 */
public interface AvatarSource {

    /**
     * Аватарка учасника або {@code null}, якщо її ще (або взагалі) немає.
     *
     * @param steamId SteamID64 рядком; {@code null} чи порожній рядок означає
     *                учасника без Steam — бота або гравця з локальної мережі
     */
    Texture avatarFor(String steamId);

    /**
     * Скільки разів набір аватарок змінювався. Зростає лише вперед.
     *
     * <p>Читається щокадру тим, хто малює: змінилось — перебудувати рядки.
     */
    int revision();

    /**
     * Кадровий такт джерела. Кличе бекенд зі свого {@code pump()}.
     *
     * <p>Тут джерело перевіряє те, чого чекає, і підіймає {@link #revision()},
     * коли щось нарешті доступне. Саме це, а не колбек, робить появу аватарки
     * гарантованою — див. javadoc класу.
     *
     * <p>GL чіпати тут НЕ можна: текстура народжується тільки в
     * {@link #avatarFor(String)}, тобто в того, хто малює.
     */
    default void update() { }

    /** Звільнити текстури. Кличе той, хто володіє бекендом, при виході з гри. */
    void dispose();

    /**
     * Джерело, у якого аватарок немає й не буде, — локальна мережа.
     *
     * <p>Не {@code null} навмисно: перевірка на порожнє джерело розповзлась би
     * по всіх місцях малювання, а «немає аватарки» вони й так уміють показувати
     * — цей стан однаково потрібен для ботів.
     */
    AvatarSource NONE = new AvatarSource() {
        @Override public Texture avatarFor(String steamId) { return null; }
        @Override public int revision()                    { return 0; }
        @Override public void dispose()                    { }
    };
}
